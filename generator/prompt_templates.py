"""
Шаблоны промптов для YandexGPT
С поддержкой grade_level из groups
"""
from typing import Dict, List, Optional

def build_task_prompt(
    profile: Dict,
    learning_style: str,
    topic: str,
    difficulty: str,
    num_questions: int,
    examples: None,  # List[Dict] = None,
    progress: Optional[Dict] = None
) -> str:
    """
    Строит промпт для генерации задания с учетом класса ученика
    """
    
    # Информация об ученике (с добавлением класса)
    student_info = f"""
ИНФОРМАЦИЯ ОБ УЧЕНИКЕ:
• Класс/курс: {profile['group']['grade_text']}
• Уровень подготовки: {profile['academic']['performance_group']} (успеваемость {profile['academic']['success_rate']:.0%})
• В среднем решает задачу за {profile['behavior']['avg_time']:.0f} секунд
• Использует подсказки в {profile['behavior']['hint_usage_rate']:.0%} случаев
• Стиль обучения: {learning_style}
"""
    
    # Информация о прогрессе
    progress_info = ""
    if progress:
        weak_topics = ', '.join(progress.get('weak_topics', [])) or 'нет'
        strong_topics = ', '.join(progress.get('strong_topics', [])) or 'нет'
        
        progress_info = f"""
ПРОГРЕСС ЗА ПОСЛЕДНЕЕ ВРЕМЯ:
• Динамика: {progress.get('trend', 'неизвестно')}
• Средний результат: {progress.get('avg_score', 0):.0%}
• Темы для повторения: {weak_topics}
• Хорошо получается: {strong_topics}
"""
    
    # Примеры из базы знаний
    examples_text = ""
    if examples:
        examples_text = "\nПРИМЕРЫ ПОХОЖИХ ЗАДАНИЙ:\n"
        for i, ex in enumerate(examples, 1):
            examples_text += f"{i}. {ex.get('text', '')}\n"
    
    # Инструкции по сложности
    difficulty_desc = {
        "очень легкий": "максимально простые, базовые примеры, одно действие",
        "легкий": "простые, 1-2 действия, целые числа",
        "средний": "умеренной сложности, могут быть дроби, скобки",
        "сложный": "требующие размышления, несколько шагов решения"
    }.get(difficulty, "средней сложности")
    
    # Цель задания
    if difficulty in ["легкий", "очень легкий"]:
        goal = "закрепить базовые навыки и повысить уверенность"
    elif difficulty == "средний":
        goal = "развить навыки и подготовить к более сложным задачам"
    else:
        goal = "дать вызов и стимулировать мышление"
    
    # Основной промпт
    prompt = f"""
Ты — опытный репетитор. Создай {num_questions} заданий по теме "{topic}".

{student_info}
{progress_info}

ОСОБЕННОСТИ ТЕКУЩЕГО ЗАДАНИЯ:
• Сложность: {difficulty} ({difficulty_desc})
• Цель: {goal}
• Количество заданий: {num_questions}

{_get_topic_instructions(topic, profile['group']['grade_level'])}

ТРЕБОВАНИЯ К ЗАДАНИЯМ:
1. Задания должны строго соответствовать сложности "{difficulty}"
2. Учитывай класс ученика: {profile['group']['grade_text']}
3. Учитывай прогресс ученика: {_get_progress_advice(progress)}
4. Для каждого задания в JSON нужно заполнить поля:
   • text — текст задания, в конце КОНКРЕТНОГО текста добавь указание формата ответа в скобках
   • hint — краткая подсказка (без ответа)
   • explanation — подробное пошаговое объяснение (без указания формата ответа)
   • answer — правильный ответ в строгом формате

Указание формата ответа должно быть частью поля text

ПРАВИЛА ФОРМАТИРОВАНИЯ ТЕКСТА ЗАДАНИЯ:
В тексте задания при необходимости укажи, как нужно записать ответ, в зависимости от типа:

• Если ответ — дробь: добавь "(Ответ запишите в виде обыкновенной дроби, например 2/3)"
• Если ответ — смешанное число: добавь "(Ответ запишите в виде смешанного числа, например 1 2/3)"
• Если ответ — два корня: добавь "(Ответ запишите через запятую в порядке возрастания, например 2, 5)"
• Если ответ — десятичная дробь: добавь "(Ответ запишите десятичной дробью, например 0,75)"
• Если в ответе есть π: добавь "(Если в ответе есть π, укажите только коэффициент, число π не пишите, например 3π → 3, π/2 → 1/2)"
• Если ответ — проценты: добавь "(Ответ запишите числом без знака %, например 25)"
• Если ответ — расстояние/время/скорость: добавь "(Ответ запишите числом без единиц измерения)"
• Если уравнение не имеет решений: добавь "(Ответ: нет решений)"
• Если решений бесконечно много: добавь "(Ответ: любое число)"

Если задание по гуманитарным наукам, оформи текст задания с вариантами ответа, чтобы в ответ нужно было ввести цифру(ы) - номер(а) правильного(ых) ответа(ов) ИЛИ чтобы ответ был ОДНИМ словом.

ПРАВИЛА ФОРМАТИРОВАНИЯ ОТВЕТОВ:
1. Если ответ — одно число: напиши только число (например: "5", "-3", "0.5")
2. Если ответ — дробь: запиши в виде простой дроби, например "2/3" (не "0.666")
3. Если ответ — смешанное число: запиши как "1 2/3" (пробел между целой частью и дробью)
4. Если ответ — два корня: запиши через запятую в порядке возрастания, например "2, 5" или "-3, 4"
5. Если ответ — десятичная дробь: используй точку, например "0.75" (не "0,75")
6. Если в ответе есть π (пи): запиши только коэффициент, например "3π" → "3", "π/2" → "1/2"
7. Если ответ — проценты: запиши число без знака %, например "25" (не "25%")
8. Если ответ — расстояние, время, скорость: только число, без единиц измерения (не "7 км", а "7")
9. Если ответ — геометрическая величина: только число (не "12 см²", а "12")
10. Если уравнение не имеет решений: напиши "нет решений"
11. Если решений бесконечно много: напиши "любое число"

ТРЕБОВАНИЯ К ПОДСКАЗКЕ:
4. Для каждого задания добавь краткую подсказку, которая:
   • НЕ содержит правильный ответ
   • Даёт направление для размышления
   • Помогает понять с чего начать решение 
   • Может содержать формулы в общем виде

Примеры ПРАВИЛЬНОГО заполнения:
Пример линейное уравнение:
{{
    "text": "Решите уравнение: 3(x - 2) + 4 = 2x + 1 (Ответ запишите в виде числа)",
    "hint": "Сначала раскрой скобки, затем перенеси все слагаемые с x в одну сторону, а числа — в другую",
    "explanation": "1. Раскрываем скобки: 3x - 6 + 4 = 2x + 1\n2. Упрощаем левую часть: 3x - 2 = 2x + 1\n3. Переносим 2x влево, -2 вправо: 3x - 2x = 1 + 2\n4. Получаем: x = 3",
    "answer": "3"
}}
Пример (с π):
{{
    "text": "Найдите длину окружности, если её радиус равен 7 см (Если в ответе есть π, укажите только коэффициент, например если получилось 3π запишите просто 3)",
    "hint": "Используй формулу длины окружности 2πR",
    "explanation": "1. Формула длины окружности: 2πR. Подставляем R = 7:  C = 2·π·7 = 14π^3. Так как нужно указать только коэффициент перед π: 14",
    "answer": "14"
}}
ВАЖНЫЕ ТЕХНИЧЕСКИЕ ТРЕБОВАНИЯ:
• НЕ ИСПОЛЬЗУЙ LaTeX разметку (\frac, \text, \sqrt)
• Для дробей пиши простым текстом: "2/3" или "1/2"
• НЕ используй обратные слеши \ в ответах
• В ответах указывай ТОЛЬКО ЧИСЛО, без слов "см", "км", "ч", "руб" и т.д.
• Например: вместо "7 км" пиши "7", вместо "3 часа" пиши "3"
• НЕ добавляй текст до или после JSON
• Начинай ответ строго с {{ и заканчивай }}

ОТВЕТ ДОЛЖЕН БЫТЬ ТОЛЬКО В ФОРМАТЕ JSON:

{{
    "questions": [
        {{
            "text": "текст задания",
            "hint": "краткая подсказка без ответа, направляющая к решению",
            "explanation": "подробное пошаговое объяснение решения",
            "answer": "правильный ответ (только число)"
        }}
    ]
}}
"""
    return prompt


def _get_topic_instructions(topic: str, grade_level: int = None) -> str:
    """Возвращает инструкции для конкретной темы с учетом класса"""
    
    # Базовая инструкция для темы
    base_instructions = {
        "линейные уравнения": """
СПЕЦИФИКА ТЕМЫ "Линейные уравнения":
• Уравнения вида ax + b = c
• Можно использовать скобки: a(x + b) = c
• Для легкого уровня: целые коэффициенты, одно действие
• Для среднего: могут быть дроби, несколько действий
• Для сложного: уравнения с дробями, скобками, переносом слагаемых
• Ответы: только число x
""",
        "квадратные уравнения": """
СПЕЦИФИКА ТЕМЫ "Квадратные уравнения":
• Уравнения вида ax² + bx + c = 0
• Для легкого уровня: целые корни, a=1
• Для среднего: дискриминант, рациональные корни
• Для сложного: иррациональные корни, параметры
• Формат ответа: два корня через запятую в порядке возрастания
• Указание в задании: "(Ответ запишите через запятую в порядке возрастания, например 2, 5)"
""",
        "дроби": """
СПЕЦИФИКА ТЕМЫ "Дроби":
• Сложение и вычитание дробей с разными знаменателями
• Умножение и деление дробей
• Сложные выражения с обыкновенными дробями
• Сокращение дробей
• Формат ответа: простая дробь (2/3) или смешанное число (1 2/3)
• Указание в задании: "(Ответ запишите в виде обыкновенной дроби, например 2/3)" или "(Ответ запишите в виде смешанного числа, например 1 2/3)"
""",
        "проценты": """
СПЕЦИФИКА ТЕМЫ "Проценты":
• Нахождение процента от числа
• Нахождение числа по его проценту
• Процентное соотношение
• Ответы: только число, без знака % и без единиц измерения
""",
        "геометрия": """
СПЕЦИФИКА ТЕМЫ "Геометрия":
• Площади и периметры фигур
• Теорема Пифагора
• Углы и треугольники
• Формат ответа: число без единиц измерения
• Если в ответе есть π: только коэффициент
• Указание в задании: "(Ответ запишите числом без единиц измерения)" или "(Если в ответе есть π: запишите только коэффициент)"
""",
        "задачи на движение": """
СПЕЦИФИКА ТЕМЫ "Задачи на движение":
• Формула: расстояние = скорость × время
• Задачи на встречное движение
• Задачи на движение в одном направлении
• Формат ответа: число без единиц измерения
• Указание в задании: "(Ответ запишите числом без единиц измерения)"
• Например: вместо "3 часа" пиши "3", вместо "120 км" пиши "120"
"""
    }
    
    # Добавляем рекомендации по классу Учитывай 4 класс (если школа) или 4 курс (если университет)
    grade_advice = ""

    topic_instruction = base_instructions.get(topic, "")
    
    return topic_instruction + grade_advice


def _get_progress_advice(progress: Optional[Dict]) -> str:
    """Возвращает советы на основе прогресса"""
    if not progress:
        return "стандартный подход"
    
    advice = []
    
    if progress.get('weak_topics'):
        advice.append(f"удели внимание темам: {', '.join(progress['weak_topics'])}")
    
    trend = progress.get('trend', '')
    if 'растёт' in trend:
        advice.append("усложняй")
    elif 'падает' in trend:
        advice.append("сделай немного проще для уверенности")
    
    return '. '.join(advice) if advice else "стандартный подход"


def build_adaptive_prompt(
    profile: Dict,
    previous_mistakes: List[str],
    current_topic: str
) -> str:
    """Формирует промпт для адаптивного задания на основе прошлых ошибок"""
    
    mistakes_text = "\n".join([f"- {m}" for m in previous_mistakes[:5]])
    
    prompt = f"""
Ученик {profile['group']['grade_text']} допустил следующие ошибки в прошлых заданиях:
{mistakes_text}

Составь 3 задания по теме "{current_topic}", которые помогут проработать эти ошибки.
Учитывай уровень подготовки: {profile['academic']['performance_group']}

Формат ответа (только JSON):
{{
    "questions": [
        {{
            "text": "задание",
            "answer": "ответ",
            "explanation": "объяснение с акцентом на типичные ошибки",
            "hint": "подсказка",
            "common_mistake": "какую ошибку предотвращает это задание"
        }}
    ]
}}"""
    
    return prompt